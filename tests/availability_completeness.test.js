"use strict";

// Availability was scored by counting array entries: three or more and the
// statement was complete.
//
// That passed the template -- "Primary runner result: <absolute path>",
// "Generated artifacts are under <absolute path>", plus a sentence about
// archiving -- and it failed the author's own two paragraphs, which name every
// shipped artifact by its package name and say which script regenerates which
// number. The count measured formatting, and the only thing it reliably rewarded
// was padding.

const test = require("node:test");
const assert = require("node:assert/strict");

const { paperRubric } = require("../src/reporting/document_reviews");

function availabilityItem(availability) {
  return paperRubric({ data_code_availability: availability })
    .find((item) => item.name === "data_code_availability");
}

const AUTHORED = [
  "The anonymous submission package contains the frozen specification, calibration, decision record, "
  + "arm summary, per-seed results, render-bank index, sham audit, three-fold audit, figure generator "
  + "and figure manifest under `artifacts/`. Primary values are regenerated from `artifacts/01-check.json` "
  + "and `artifacts/04-active_boundary_arm_summary.csv`.",
  "A reader can run `artifacts/13-script.py` with `artifacts/01-check.json` and compare its outputs with "
  + "`artifacts/10-active_boundary_per_seed_results.csv`. Figures are regenerated by "
  + "`artifacts/08-draw_figures.py`.",
];

const TEMPLATE = [
  "Primary runner result: /opt/researchlab/.research-lab/artifacts/stats/cycle/followup-runner-128/result.json.",
  "Generated analysis artifacts are under /opt/researchlab/.research-lab/artifacts/stats/cycle/followup-runner-128.",
  "Source identifiers, generated tables, sensitivity notes, and bias/missing-data disclosures are archived with the runtime outputs when available.",
];

test("two paragraphs that say what ships and how to rebuild it are complete", () => {
  const item = availabilityItem(AUTHORED);
  assert.deepEqual(item.reasons, []);
});

test("the template's three lines no longer pass on their count alone", () => {
  // It names paths but never says how a reader regenerates a reported number,
  // which is the half that makes an availability statement usable.
  const item = availabilityItem(TEMPLATE);
  assert.equal(item.reasons.length, 1);
  assert.match(item.reasons[0], /how the reported numbers are regenerated/);
});

test("each missing half is named, so the author is told what to write", () => {
  const noArtifacts = availabilityItem([
    "The numbers can be regenerated by re-running the analysis script end to end, which recomputes every "
    + "reported value from the recorded inputs and writes them out again for comparison against the paper.",
  ]);
  assert.match(noArtifacts.reasons[0], /does not name what ships/);

  const tooShort = availabilityItem(["Artifacts are archived."]);
  assert.match(tooShort.reasons[0], /too short/);

  const empty = availabilityItem([]);
  assert.match(empty.reasons[0], /too short/);
});
