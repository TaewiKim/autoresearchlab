"use strict";

const path = require("path");
const { asArray, uniqueStrings } = require("./reviews/gate/utils");
const { selectedLeadIdentity, reviewMatchesSelectedLead } = require("../agents/shared/lead_evidence_match");

function normalizeBlockerForMatch(value) {
  return String(value || "")
    .toLowerCase()
    // Keep letters and digits in any script; a blocker written in another
    // language must still normalise to something matchable.
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function blockerTextsMatch(left, right) {
  const a = normalizeBlockerForMatch(left);
  const b = normalizeBlockerForMatch(right);
  if (!a || !b) return false;
  if (a === b) return true;
  const minLength = Math.min(a.length, b.length);
  return minLength >= 24 && (a.includes(b) || b.includes(a));
}

function applyGateBlockerAdjudications(blockers, adjudications) {
  const active = [];
  const removed = [];
  const downgraded = [];
  const upheld = [];
  const decisions = asArray(adjudications)
    .filter((item) => item && typeof item === "object" && item.blocker)
    .map((item) => ({
      ...item,
      decision: String(item.decision || "").trim().toLowerCase(),
    }));

  for (const blocker of asArray(blockers)) {
    const matching = decisions.find((item) => blockerTextsMatch(blocker, item.blocker));
    if (!matching) {
      active.push(blocker);
      continue;
    }
    if (["remove", "resolved", "superseded"].includes(matching.decision)) {
      removed.push({ blocker, adjudication: matching });
      continue;
    }
    if (matching.decision === "downgrade") {
      downgraded.push({ blocker, adjudication: matching });
      continue;
    }
    upheld.push({ blocker, adjudication: matching });
    active.push(blocker);
  }

  return {
    active_blockers: uniqueStrings(active),
    removed_blockers: removed,
    downgraded_blockers: downgraded,
    upheld_blockers: upheld,
  };
}

// MEASURED ON cycle-a-20260919, 2026-11-06: the independent gate
// retired objections, but downstream reviews regenerated them from heuristics.
// Consume the gate's applied dispositions, not Director requests or lane-local
// patches. This changes reasons only: scores, conjunctions and raw audits stay.
function applyPublishedGateDispositions({ root, cycleId, rubric, blockers, fs = require("fs") }) {
  let gate;
  try {
    gate = JSON.parse(fs.readFileSync(path.join(root, "state", `${cycleId}-gate-review.json`), "utf8"));
  } catch {
    return { rubric, blockers, gate_blocker_adjudication_resolution: null };
  }
  if (!reviewMatchesSelectedLead(gate, selectedLeadIdentity(root, cycleId))) {
    return { rubric, blockers, gate_blocker_adjudication_resolution: null };
  }
  // MEASURED ON cycle-a-20260919, 2026-11-09: at owner_selection,
  // six Chronicle lanes completed while Director 1906 still asked to sync
  // supersessions. A gate's applied subset is not the decision register: an
  // objection absent from that build can still be regenerated by another sink.
  // Resolve each sink's reasons from the same published independent decisions.
  const published = gate.gate_blocker_adjudication_resolution;
  const adjudications = Array.isArray(gate.gate_blocker_adjudications)
    ? gate.gate_blocker_adjudications
    : [ // Compatibility with receipts published before the full register.
      ...(published?.removed_blockers || []),
      ...(published?.downgraded_blockers || []),
      ...(published?.upheld_blockers || []),
    ].map((item) => ({ ...item.adjudication, blocker: item.blocker }));
  if (!published && !adjudications.length) {
    return { rubric, blockers, gate_blocker_adjudication_resolution: null };
  }
  const resolution = applyGateBlockerAdjudications(uniqueStrings([
    ...blockers, ...rubric.flatMap((item) => item.reasons || []),
  ]), adjudications);
  const retired = new Set([
    ...resolution.removed_blockers, ...resolution.downgraded_blockers,
  ].map((item) => item.blocker));
  const keep = (text) => !retired.has(text);
  return {
    rubric: rubric.map((item) => ({ ...item, reasons: (item.reasons || []).filter(keep) })),
    blockers: blockers.filter(keep),
    gate_blocker_adjudication_resolution: resolution,
  };
}

module.exports = { applyGateBlockerAdjudications, applyPublishedGateDispositions };
